"""LoRA fine-tuning & evaluation for specializing LiquidAI/LFM2.5-1.2B-Instruct on Layer 4.

Trains a compact LoRA adapter (rank 16, bf16) on the strictly disjoint ChatML
distillation corpus generated by `scripts/build_layer4_dataset.py` (500 train /
100 val), targeting the Stage-2 multi-button switching gap observed in zero-shot
LFM2.5-1.2B runs (16/20 -> 20/20 target).

Optional `--eval-ablation` runs our exact 20-episode controlled ablation (Ch 1-7
+ M1-M3, both Phase 1 scripted and Phase 2B neural) directly against the fine-tuned
model in PyTorch and saves a JSON comparison report.

Requires optional ML packages in `.venv` (see `requirements-lora.txt`).
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))


def _run_hf_ablation(
    model: Any,
    tokenizer: Any,
    model_label: str,
    device: str,
    out_path: str,
) -> dict[str, Any]:
    """Evaluate a loaded HF causal LM directly inside Portal-ML's FourLayerAgent."""
    import torch

    from portal_ml.bt.ast import parse_bt
    from portal_ml.bt.evaluator import BehaviorTreeEvaluator
    from portal_ml.motor.hybrid import HybridMotorController
    from portal_ml.motor.neural import NeuralAimPolicy, NeuralMoveToPolicy
    from portal_ml.planner import (
        MULTI_STAGE_BENCHMARKS,
        SYSTEM_PROMPT,
        FourLayerAgent,
        NullStrategicPlanner,
        StrategicDirective,
        build_symbolic_digest,
        compile_semantic_action,
        strip_reasoning_and_extract_json,
    )
    from portal_ml.sim.chambers import CHAMBERS
    from portal_ml.sim.mock_env import MockPortalEnv

    model.eval()

    class _LocalHFPlanner:
        name = f"hf:{model_label}"

        def __init__(self) -> None:
            self.calls = 0
            self.fallbacks = 0

        def plan(self, snapshot: Any, memory: Any, trigger: Any, current: Any = None) -> StrategicDirective:
            self.calls += 1
            digest = build_symbolic_digest(snapshot, memory, trigger, current)
            messages = [
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": digest},
            ]
            prompt = tokenizer.apply_chat_template(
                messages, tokenize=False, add_generation_prompt=True
            )
            inputs = tokenizer(prompt, return_tensors="pt").to(device)
            with torch.inference_mode():
                gen = model.generate(
                    **inputs,
                    max_new_tokens=96,
                    do_sample=False,
                    pad_token_id=tokenizer.pad_token_id,
                    eos_token_id=tokenizer.eos_token_id,
                )
            new_tokens = gen[0][inputs["input_ids"].shape[1] :]
            raw = tokenizer.decode(new_tokens, skip_special_tokens=True)
            try:
                payload = strip_reasoning_and_extract_json(raw)
                return compile_semantic_action(
                    snapshot,
                    action=str(payload["action"]),
                    cube_id=payload.get("cube_id"),
                    button_id=payload.get("button_id"),
                    pedestal_id=payload.get("pedestal_id"),
                    exit_id=payload.get("exit_id"),
                )
            except Exception:
                self.fallbacks += 1
                return NullStrategicPlanner().plan(snapshot, memory, trigger, current)

    tree = parse_bt(Path("champions/seed7_decoupled.bt").read_text(encoding="utf-8"))
    hybrid_2b = HybridMotorController(
        moveto_policy=NeuralMoveToPolicy.load("champions/moveto_mlp.json"),
        aim_policy=NeuralAimPolicy.load("champions/aim_mlp.json"),
    )

    env = MockPortalEnv()
    report: dict[str, Any] = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "model": model_label,
        "bt_path": "champions/seed7_decoupled.bt",
        "results": {},
    }

    for motor_name, hybrid in (("scripted", None), ("neural_2b", hybrid_2b)):
        std_rows = []
        for cid in sorted(CHAMBERS.keys()):
            planner = _LocalHFPlanner()
            agent = FourLayerAgent(BehaviorTreeEvaluator(tree), planner=planner, hybrid_motor=hybrid)
            m = agent.run_episode(env, chamber_id=cid)
            row = m.to_dict()
            row["fallback_count"] = planner.fallbacks
            std_rows.append(row)

        ms_rows = []
        for key, spec in MULTI_STAGE_BENCHMARKS.items():
            planner = _LocalHFPlanner()
            agent = FourLayerAgent(BehaviorTreeEvaluator(tree), planner=planner, hybrid_motor=hybrid)
            m = agent.run_episode(env, spec=spec)
            row = m.to_dict()
            row["fallback_count"] = planner.fallbacks
            ms_rows.append(row)

        tot_calls = sum(r["planner_calls"] for r in std_rows + ms_rows)
        tot_ms = sum(r["total_planner_ms"] for r in std_rows + ms_rows)
        tot_fb = sum(r["fallback_count"] for r in std_rows + ms_rows)
        std_ok = sum(1 for r in std_rows if r["success"])
        ms_ok = sum(1 for r in ms_rows if r["success"])

        report["results"][motor_name] = {
            "standard_passed": std_ok,
            "standard_total": len(std_rows),
            "multistage_passed": ms_ok,
            "multistage_total": len(ms_rows),
            "total_planner_calls": tot_calls,
            "avg_planner_ms": round(tot_ms / max(1, tot_calls), 2),
            "total_fallbacks": tot_fb,
            "standard": std_rows,
            "multistage": ms_rows,
        }
        print(
            f"\n=== {model_label} [{motor_name}] | Standard: {std_ok}/{len(std_rows)} "
            f"| Multi-Stage: {ms_ok}/{len(ms_rows)} | Calls: {tot_calls} "
            f"(avg {tot_ms / max(1, tot_calls):.0f}ms) | Fallbacks: {tot_fb} ==="
        )
        for row in ms_rows:
            st = "PASS" if row["success"] else "FAIL"
            print(
                f"  [multistage] {row['chamber_name'][:28]:28s} {st:4s} | steps={row['steps']:3d} "
                f"| calls={row['planner_calls']:2d} ({row['total_planner_ms']:.0f}ms) "
                f"| triggers={row['planner_triggers']}"
            )

    if out_path:
        p = Path(out_path)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(f"\nSaved LoRA ablation report -> {p}")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(description="LoRA-finetune LFM2.5-1.2B on Layer-4 traces.")
    parser.add_argument("--model", default="LiquidAI/LFM2.5-1.2B-Instruct")
    parser.add_argument("--train-jsonl", default="records/layer4_distill_train.jsonl")
    parser.add_argument("--val-jsonl", default="records/layer4_distill_val.jsonl")
    parser.add_argument("--out-dir", default="champions/lfm25_layer4_lora")
    parser.add_argument("--gpu", default="1", help="Physical CUDA GPU index (1 = RTX 5060 Ti 16GB, 0 = RTX 4070 12GB)")
    parser.add_argument("--epochs", type=int, default=3)
    parser.add_argument("--batch-size", type=int, default=4)
    parser.add_argument("--lr", type=float, default=2e-4)
    parser.add_argument("--lora-r", type=int, default=16)
    parser.add_argument("--merge", action="store_true", help="Merge LoRA weights into standalone HF model")
    parser.add_argument("--eval-ablation", default="", help="Optional JSON report path to run 20-episode ablation post-training")
    args = parser.parse_args()

    missing = []
    for pkg in ("torch", "transformers", "peft", "trl", "datasets"):
        try:
            __import__(pkg)
        except ImportError:
            missing.append(pkg)
    if missing:
        print(
            "Optional LoRA training packages not installed in this Python environment: "
            + ", ".join(missing)
        )
        print("Install inside `.venv` with CUDA 12.8 PyTorch:")
        print("  python -m venv .venv")
        print("  .venv\\Scripts\\pip install --index-url https://download.pytorch.org/whl/cu128 torch")
        print("  .venv\\Scripts\\pip install -r requirements-lora.txt")
        return 2

    if args.gpu and "CUDA_VISIBLE_DEVICES" not in os.environ:
        os.environ["CUDA_VISIBLE_DEVICES"] = str(args.gpu)

    import torch
    from datasets import load_dataset
    from peft import LoraConfig
    from transformers import AutoModelForCausalLM, AutoTokenizer
    from trl import SFTConfig, SFTTrainer

    device = "cuda:0" if torch.cuda.is_available() else "cpu"
    if torch.cuda.is_available():
        torch.cuda.set_device(0)
        gpu_name = torch.cuda.get_device_name(0)
    else:
        gpu_name = "cpu"

    dtype = torch.bfloat16 if torch.cuda.is_available() and torch.cuda.is_bf16_supported() else torch.float16
    print(f"Loading {args.model} on {device} ({gpu_name}, {dtype})...")
    t0 = time.perf_counter()

    tokenizer = AutoTokenizer.from_pretrained(args.model)
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    model = AutoModelForCausalLM.from_pretrained(
        args.model,
        dtype=dtype,
    ).to(device)

    ds = load_dataset(
        "json",
        data_files={"train": args.train_jsonl, "validation": args.val_jsonl},
    )

    peft_cfg = LoraConfig(
        r=args.lora_r,
        lora_alpha=args.lora_r * 2,
        lora_dropout=0.05,
        bias="none",
        task_type="CAUSAL_LM",
        target_modules="all-linear",
    )

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    sft_cfg = SFTConfig(
        output_dir=str(out_dir),
        num_train_epochs=args.epochs,
        per_device_train_batch_size=args.batch_size,
        gradient_accumulation_steps=4,
        learning_rate=args.lr,
        bf16=(dtype == torch.bfloat16),
        fp16=(dtype == torch.float16),
        logging_steps=10,
        eval_strategy="epoch",
        save_strategy="no",
        max_length=1024,
        report_to="none",
    )

    trainer = SFTTrainer(
        model=model,
        args=sft_cfg,
        train_dataset=ds["train"],
        eval_dataset=ds["validation"],
        processing_class=tokenizer,
        peft_config=peft_cfg,
    )
    train_res = trainer.train()
    elapsed = time.perf_counter() - t0
    print(
        f"Training done in {elapsed:.1f}s | train_loss={train_res.training_loss:.4f}"
    )

    adapter_dir = out_dir / "adapter"
    trainer.save_model(str(adapter_dir))
    tokenizer.save_pretrained(str(adapter_dir))
    print(f"Saved LoRA adapter -> {adapter_dir}")

    eval_model = trainer.model
    if args.merge:
        eval_model = trainer.model.merge_and_unload()
        merged_dir = out_dir / "merged"
        eval_model.save_pretrained(str(merged_dir))
        tokenizer.save_pretrained(str(merged_dir))
        print(f"Saved merged HF model -> {merged_dir}")

    if args.eval_ablation:
        _run_hf_ablation(
            eval_model,
            tokenizer,
            f"{args.model}+lora(r={args.lora_r})",
            device,
            args.eval_ablation,
        )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
